  function normFill(s) {
    if (s === undefined || s === null) return '';
    return String(s)
      .replace(/[\uFF01-\uFF5E]/g, function (ch) {
        return String.fromCharCode(ch.charCodeAt(0) - 0xFEE0);
      })
      .replace(/％/g, '%')
      .trim()
      .replace(/\s+/g, ' ')
      .toLowerCase();
  }

  function isAnswered(q, pick) {
    if (!q || pick === undefined || pick === null) return false;
    if (q.type === 'multi') return Array.isArray(pick) && pick.length > 0;
    if (q.type === 'fill') return typeof pick === 'string' && normFill(pick).length > 0;
    return Number.isInteger(pick) && pick >= 0 && q.options && pick < q.options.length;
  }

  function check(q, pick) {
    if (!isAnswered(q, pick)) return false;
    if (q.type === 'multi') {
      var a = (q.answer || []).slice().sort(function (x, y) { return x - y; });
      var seen = {};
      var b = pick.filter(function (x) {
        if (!Number.isInteger(x) || x < 0 || x >= q.options.length || seen[x]) return false;
        seen[x] = true;
        return true;
      }).sort(function (x, y) { return x - y; });
      if (a.length !== b.length) return false;
      for (var i = 0; i < a.length; i++) {
        if (a[i] !== b[i]) return false;
      }
      return true;
    }
    if (q.type === 'fill') {
      var v = normFill(pick);
      return (q.accept || []).some(function (cand) {
        return normFill(cand) === v;
      });
    }
    return pick === q.answer;
  }

  function formatAnswer(q) {
    var letters = ['A', 'B', 'C', 'D', 'E'];
    if (q.type === 'multi') {
      return (q.answer || []).map(function (i) { return letters[i] || String(i); }).join('、');
    }
    if (q.type === 'fill') {
      return q.answerText || ((q.accept && q.accept[0]) || '');
    }
    return letters[q.answer] || String(q.answer);
  }

  function byExp(expId) {
    return QUESTIONS.filter(function (q) { return q.exp === expId; });
  }

  function filter(opts) {
    opts = opts || {};
    var topic = opts.topic || 'all';
    var diff = opts.diff || 'all';
    var qtype = opts.type || 'all';
    return QUESTIONS.filter(function (q) {
      if (topic !== 'all' && q.topic !== topic) return false;
      if (diff !== 'all' && q.diff !== diff) return false;
      if (qtype !== 'all' && q.type !== qtype) return false;
      return true;
    });
  }

  /* 确定性洗牌 / 随机抽题（支持固定种子或随机） */
  function sample(list, n, seed) {
    var arr = list.slice();
    var rnd = seed != null ? (function (s) {
      var a = s >>> 0;
      return function () {
        a = (a + 0x6D2B79F5) >>> 0;
        var t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
      };
    })(seed) : Math.random;
    for (var i = arr.length - 1; i > 0; i--) {
      var j = Math.floor(rnd() * (i + 1));
      var tmp = arr[i]; arr[i] = arr[j]; arr[j] = tmp;
    }
    return arr.slice(0, Math.min(n, arr.length));
  }

  /* 统计做题进度与各实验掌握情况 */
  function stats(answers, subset) {
    var list = subset || QUESTIONS;
    var ans = answers || {};
    var answered = 0, correct = 0, wrongIds = [];
    list.forEach(function (q) {
      var pick = ans[q.id];
      if (!isAnswered(q, pick)) return;
      answered++;
      if (check(q, pick)) correct++;
      else wrongIds.push(q.id);
    });
    var acc = answered ? Math.round((correct / answered) * 1000) / 10 : null;
    var progress = list.length ? Math.round((answered / list.length) * 1000) / 10 : 0;
    return {
      total: list.length,
      answered: answered,
      correct: correct,
      wrong: wrongIds.length,
      wrongIds: wrongIds,
      accuracy: acc,
      progress: progress
    };
  }

